-- Complete schema for a fresh Customer Inquiry System database.
-- Run this file once against a NEW / EMPTY PostgreSQL database.
-- Includes all tables, constraints, indexes, and the attachment-limit trigger.

BEGIN;

-- 1. Users
CREATE TABLE IF NOT EXISTS public.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'INTAKE', 'HANDLER')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  specialization VARCHAR(30),
  CONSTRAINT users_specialization_check
    CHECK (specialization IS NULL OR specialization IN ('TECHNICAL', 'REPAIR', 'BILLING', 'GENERAL')),
  CONSTRAINT users_handler_specialization_check
    CHECK ((role = 'HANDLER' AND specialization IS NOT NULL)
        OR (role <> 'HANDLER' AND specialization IS NULL))
);

CREATE INDEX IF NOT EXISTS users_role_is_active_idx
  ON public.users (role, is_active);

-- 2. Inquiry categories
CREATE TABLE IF NOT EXISTS public.inquiry_categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO public.inquiry_categories (name)
VALUES ('GENERAL'), ('TECHNICAL'), ('REPAIR'), ('BILLING')
ON CONFLICT (name) DO NOTHING;

-- 3. Inquiries
CREATE TABLE IF NOT EXISTS public.inquiries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR(100) NOT NULL,
  contact VARCHAR(150) NOT NULL,
  subject VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'NEW'
    CHECK (status IN ('NEW', 'IN_PROGRESS', 'RESOLVED')),
  created_by INTEGER NOT NULL REFERENCES public.users(id),
  assigned_to INTEGER REFERENCES public.users(id),
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  category VARCHAR(30) NOT NULL DEFAULT 'GENERAL'
    REFERENCES public.inquiry_categories(name)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  assignment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
    CHECK (assignment_status IN ('PENDING', 'ASSIGNED')),
  handler_response_status VARCHAR(20) NOT NULL DEFAULT 'NOT_REQUIRED'
    CHECK (handler_response_status IN ('WAITING', 'ACCEPTED', 'DECLINED', 'NOT_REQUIRED', 'UNKNOWN')),
  decline_reason TEXT,
  responded_at TIMESTAMP WITHOUT TIME ZONE,
  accepted_at TIMESTAMP WITHOUT TIME ZONE,
  resolved_at TIMESTAMP WITHOUT TIME ZONE,
  customer_email VARCHAR(255),
  customer_informed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_inquiries_status
  ON public.inquiries (status);
CREATE INDEX IF NOT EXISTS idx_inquiries_created_by
  ON public.inquiries (created_by);
CREATE INDEX IF NOT EXISTS idx_inquiries_assigned_to
  ON public.inquiries (assigned_to);
-- Retained because this index also exists in the supplied database export.
CREATE INDEX IF NOT EXISTS inquiries_assigned_to_idx
  ON public.inquiries (assigned_to);
CREATE INDEX IF NOT EXISTS inquiries_handler_status_idx
  ON public.inquiries (assigned_to, status, handler_response_status);

-- 4. Inquiry attachments
-- Stores uploaded file metadata/path. The binary content is stored by the app
-- at file_path; inquiry_evidence below is a separate BYTEA-based table.
CREATE TABLE IF NOT EXISTS public.inquiry_attachments (
  id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  inquiry_id INTEGER NOT NULL REFERENCES public.inquiries(id) ON DELETE CASCADE,
  original_name VARCHAR(255) NOT NULL,
  stored_name VARCHAR(255) NOT NULL,
  file_path TEXT NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  file_size BIGINT NOT NULL,
  uploaded_by INTEGER,
  uploaded_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  file_type VARCHAR(20),
  CONSTRAINT chk_attachment_file_type
    CHECK (file_type IN ('image', 'document'))
);

CREATE INDEX IF NOT EXISTS idx_inquiry_attachments_inquiry_id
  ON public.inquiry_attachments (inquiry_id);

-- Allow a maximum of 3 attachments per inquiry and file type.
CREATE OR REPLACE FUNCTION public.check_inquiry_attachment_limit()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  attachment_count INTEGER;
BEGIN
  SELECT COUNT(*)
    INTO attachment_count
    FROM public.inquiry_attachments
   WHERE inquiry_id = NEW.inquiry_id
     AND file_type = NEW.file_type;

  IF attachment_count >= 3 THEN
    RAISE EXCEPTION 'Maximum 3 attachments allowed per file type';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_attachment_limit
  ON public.inquiry_attachments;

CREATE TRIGGER trg_attachment_limit
BEFORE INSERT ON public.inquiry_attachments
FOR EACH ROW
EXECUTE FUNCTION public.check_inquiry_attachment_limit();

-- 5. Inquiry assignment history/workflow
CREATE TABLE IF NOT EXISTS public.inquiry_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inquiry_id INTEGER NOT NULL REFERENCES public.inquiries(id) ON DELETE CASCADE,
  handler_id INTEGER NOT NULL REFERENCES public.users(id),
  assigned_by INTEGER REFERENCES public.users(id),
  status VARCHAR(24) NOT NULL
    CHECK (status IN ('PENDING_ACCEPTANCE', 'ACCEPTED', 'DECLINED', 'REASSIGNED', 'RESOLVED')),
  decline_reason TEXT,
  assigned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  accepted_at TIMESTAMP WITHOUT TIME ZONE,
  declined_at TIMESTAMP WITHOUT TIME ZONE,
  resolved_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX IF NOT EXISTS inquiry_assignments_inquiry_idx
  ON public.inquiry_assignments (inquiry_id, assigned_at DESC);

-- 6. User notifications
CREATE TABLE IF NOT EXISTS public.user_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  inquiry_id INTEGER REFERENCES public.inquiries(id) ON DELETE CASCADE,
  kind VARCHAR(40) NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  read_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX IF NOT EXISTS user_notifications_user_idx
  ON public.user_notifications (user_id, created_at DESC);

-- 7. Inquiry evidence (binary file data)
CREATE TABLE IF NOT EXISTS public.inquiry_evidence (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inquiry_id INTEGER NOT NULL REFERENCES public.inquiries(id) ON DELETE CASCADE,
  file_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  file_data BYTEA NOT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS inquiry_evidence_inquiry_id_idx
  ON public.inquiry_evidence (inquiry_id);

-- 8. Inquiry history
CREATE TABLE IF NOT EXISTS public.inquiry_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inquiry_id INTEGER NOT NULL REFERENCES public.inquiries(id) ON DELETE CASCADE,
  changed_by INTEGER NOT NULL REFERENCES public.users(id),
  action VARCHAR(30) NOT NULL,
  old_value TEXT,
  new_value TEXT,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT inquiry_history_action_check
    CHECK (action IN (
      'CREATED', 'ASSIGNED', 'STATUS_CHANGED', 'ACCEPTED', 'DECLINED',
      'REASSIGNED', 'CATEGORY_CHANGED', 'RESOLVED'
    ))
);

CREATE INDEX IF NOT EXISTS idx_history_inquiry_id
  ON public.inquiry_history (inquiry_id);

-- 9. Assignment state
CREATE TABLE IF NOT EXISTS public.assignment_state (
  category VARCHAR(40) PRIMARY KEY
    REFERENCES public.inquiry_categories(name)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  last_assigned_handler_id INTEGER
    REFERENCES public.users(id) ON DELETE SET NULL,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 10. PostgreSQL session storage used by Express.
CREATE TABLE IF NOT EXISTS public.user_sessions (
  sid VARCHAR NOT NULL PRIMARY KEY,
  sess JSON NOT NULL,
  expire TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS "IDX_session_expire"
  ON public.user_sessions (expire);

COMMIT;
